// Bundles the drizzle/ migrations into src/db/migrations.ts, since the database runs in the browser and can't read
// them from disk. Runs before `next dev` and `next build`; run `npm run db:bundle` after `drizzle-kit generate`.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { readMigrationFiles } from "drizzle-orm/migrator";

const root = path.join(import.meta.dirname, "..");
const migrations = readMigrationFiles({ migrationsFolder: path.join(root, "drizzle") });
const out = path.join(root, "src/db/migrations.ts");
writeFileSync(
  out,
  `// Generated by scripts/bundle-migrations.ts from drizzle/. Do not edit.\n` +
    `import type { MigrationMeta } from "drizzle-orm/migrator";\n\n` +
    `export const migrations: MigrationMeta[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Bundled ${migrations.length} migrations into ${path.relative(root, out)}`);
